#!/usr/bin/env bash
# BiliReader — free disk space used by CEF/Rust builds.
#
# Default is a dry run: it prints what would be deleted and how much that
# frees. Pass --yes to actually delete. Only build output and the CEF download
# cache are removed; sources, dependencies and the artifact drop in dist/ are
# never touched (see the `forbidden` list below).
#
# Usage:
#   scripts/bilireader-clean.sh          # dry run
#   scripts/bilireader-clean.sh --yes    # delete

set -euo pipefail

script_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
repo_root="$(dirname -- "$script_dir")"

confirm=0
case "${1:-}" in
  --yes) confirm=1 ;;
  "") ;;
  -h | --help)
    printf 'usage: %s [--yes]\n' "$0"
    exit 0
    ;;
  *)
    printf 'error: unknown argument: %s (usage: %s [--yes])\n' "$1" "$0" >&2
    exit 2
    ;;
esac

# Removable: regenerated by the next build (Rust/CEF output, CEF download).
targets=(
  "$repo_root/target/release"
  "$repo_root/target/debug"
  "$HOME/.cache/tauri-cef"
)

# Never removable, whatever the arguments or symlinks say.
forbidden=(
  "$repo_root/node_modules"
  "$repo_root/.git"
  "$repo_root/dist"
  "$HOME/.cargo"
  "$HOME/.cache/uv"
  "$HOME/.cache/pip"
)

for target in "${targets[@]}"; do
  for keep in "${forbidden[@]}"; do
    case "$target" in
      "$keep" | "$keep"/*)
        printf 'error: refusing to delete %s (covered by %s)\n' "$target" "$keep" >&2
        exit 1
        ;;
    esac
  done
done

printf '==> disk before\n'
df -h /
printf '\n'

total_kb=0
for target in "${targets[@]}"; do
  if [ -e "$target" ]; then
    size_kb="$(du -sk -- "$target" | cut -f1)"
    total_kb=$((total_kb + size_kb))
    printf '  %6s  %s\n' "$(du -sh -- "$target" | cut -f1)" "$target"
  else
    printf '  %6s  %s\n' '-' "$target (absent)"
  fi
done
printf '\n  %s ~%s GiB\n' \
  "$([ "$confirm" -eq 1 ] && printf 'freeing' || printf 'would free')" \
  "$((total_kb / 1024 / 1024))"

if [ "$confirm" -eq 0 ]; then
  printf '\ndry run: nothing deleted. Re-run with --yes to delete.\n'
else
  printf '\n'
  for target in "${targets[@]}"; do
    [ -e "$target" ] || continue
    printf 'deleting %s\n' "$target"
    rm -rf -- "$target"
  done
fi

printf '\n==> disk after\n'
df -h /
